// Generates src/generated/templates.ts from templates/<id>/v<N>.json (no fs at runtime, typed variable names).
// Fails the build on: a bad id or file name, a version that does not match the file, an unknown purpose or
// effort, a placeholder that is not declared or a declared variable that is never used, and a variable whose name
// is a denylisted customer field (the same list the runtime guard uses, src/denylist.ts).
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(here, '../templates');
const OUT = resolve(here, '../src/generated');
const PURPOSES = ['drafting', 'classification'];
const EFFORTS = ['low', 'medium', 'high'];
const ID = /^[a-z][a-z0-9-]*$/;
const VAR = /^[a-z][A-Za-z0-9]*$/;
const PLACEHOLDER = /\{\{\s*([A-Za-z0-9_]+)\s*\}\}/g;

// keep in sync with src/denylist.ts (a test asserts they match)
const denylistSource = readFileSync(resolve(here, '../src/denylist.ts'), 'utf8');
const denied = new Set(
  [...denylistSource.matchAll(/^\s*'([a-zA-Z0-9_]+)',$/gm)].map((m) =>
    m[1].toLowerCase().replace(/[_-]/g, ''),
  ),
);

const fail = (msg) => {
  throw new Error(`templates: ${msg}`);
};

const entries = [];
for (const id of readdirSync(ROOT, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()) {
  if (!ID.test(id)) fail(`template directory "${id}" is not kebab-case`);
  for (const file of readdirSync(join(ROOT, id)).sort()) {
    const m = /^v(\d+)\.json$/.exec(file);
    if (!m) fail(`${id}/${file}: files are named v<N>.json`);
    const t = JSON.parse(readFileSync(join(ROOT, id, file), 'utf8'));
    const where = `${id}/${file}`;
    if (t.id !== id) fail(`${where}: id "${t.id}" does not match its directory`);
    if (t.version !== Number(m[1]))
      fail(`${where}: version ${t.version} does not match the file name`);
    if (!PURPOSES.includes(t.purpose))
      fail(`${where}: purpose must be one of ${PURPOSES.join(', ')}`);
    if (!EFFORTS.includes(t.effort)) fail(`${where}: effort must be one of ${EFFORTS.join(', ')}`);
    if (!Number.isInteger(t.maxTokens) || t.maxTokens < 1 || t.maxTokens > 8192)
      fail(`${where}: maxTokens 1..8192`);
    if (typeof t.system !== 'string' || typeof t.user !== 'string')
      fail(`${where}: system and user are strings`);
    if (typeof t.description !== 'string' || !t.description)
      fail(`${where}: a description is required`);
    const declared = Object.keys(t.variables ?? {});
    for (const v of declared) {
      if (!VAR.test(v)) fail(`${where}: variable "${v}" must be camelCase`);
      if (denied.has(v.toLowerCase()))
        fail(`${where}: variable "${v}" is a denylisted customer field`);
    }
    const used = new Set([...`${t.system}\n${t.user}`.matchAll(PLACEHOLDER)].map((x) => x[1]));
    for (const u of used)
      if (!declared.includes(u)) fail(`${where}: placeholder {{${u}}} is not declared`);
    for (const d of declared)
      if (!used.has(d)) fail(`${where}: variable "${d}" is declared but never used`);
    entries.push({ key: `${id}@${t.version}`, template: { ...t, variableNames: declared } });
  }
}
if (entries.length === 0) fail('no templates found');

const raw = [
  '// GENERATED by scripts/generate.mjs — do not edit. Source: packages/ai/templates/<id>/v<N>.json',
  '/* eslint-disable */',
  `export const TEMPLATES = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.key, e.template])), null, 2)} as const;`,
  '',
  'export interface TemplateVariableNames {',
  ...entries.map(
    (e) => `  '${e.key}': ${e.template.variableNames.map((v) => `'${v}'`).join(' | ') || 'never'};`,
  ),
  '}',
  '',
].join('\n');

// formatted with the repo's prettier config, so the committed file passes `pnpm format:check` as generated
mkdirSync(OUT, { recursive: true });
const target = join(OUT, 'templates.ts');
const prettier = await import('prettier');
const ts = await prettier.format(raw, {
  ...(await prettier.resolveConfig(target)),
  filepath: target,
});
if (!existsSync(target) || readFileSync(target, 'utf8') !== ts) writeFileSync(target, ts);
console.log(`ai: generated ${entries.length} template(s)`);
